#!/usr/bin/env node
// Import the Obsidian migraine CSV into Aura's D1.
//
//   node scripts/import-obsidian.mjs --csv <path>                  # dry run (default)
//   node scripts/import-obsidian.mjs --csv <path> --out import.sql # write the SQL
//   npx wrangler d1 execute aura --local  --file=import.sql        # apply locally
//   npx wrangler d1 execute aura --remote --file=import.sql        # apply to prod
//
// Dry run writes nothing and touches no database. The generated SQL is idempotent
// (keyed on source_file), so re-running it is safe.
//
// The generated .sql contains personal health data. It is gitignored. Do not commit it.

import { readFileSync, writeFileSync } from "node:fs";
import { rowToEpisode, episodeToSql, locationForDate } from "./lib/obsidian.mjs";

function parseArgs(argv) {
  const a = { csv: null, out: null };
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === "--csv") a.csv = argv[++i];
    else if (argv[i] === "--out") a.out = argv[++i];
  }
  return a;
}

/** RFC4180-ish CSV parser: handles quoted fields, embedded commas and newlines. */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = "", inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows
    .filter((r) => r.some((v) => v.trim() !== ""))
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ""])));
}

const args = parseArgs(process.argv);
if (!args.csv) {
  console.error("usage: node scripts/import-obsidian.mjs --csv <path> [--out <file.sql>]");
  process.exit(1);
}

const rows = parseCsv(readFileSync(args.csv, "utf8"));

const episodes = [];
const warnings = [];
const errors = [];
let sampleCount = 0;

for (const r of rows) {
  const res = rowToEpisode(r);
  warnings.push(...res.warnings);
  if (!res.episode) { errors.push(...res.warnings); continue; }
  episodes.push(res);
  sampleCount += res.samples.length;
}

// ── Report ──────────────────────────────────────────────────────────────────
const byMonth = {};
for (const { episode } of episodes) {
  const m = episode.local_date.slice(0, 7);
  byMonth[m] = (byMonth[m] || 0) + 1;
}
const timeKnown = episodes.filter((e) => e.episode.started_at_time_known).length;
const withSeverity = episodes.filter((e) => e.episode.severity !== null).length;
const quarantinedTypes = new Set(episodes.map((e) => e.episode.self_reported_type).filter(Boolean));
const places = new Set(episodes.map((e) => locationForDate(e.episode.local_date)?.place));

console.log("=== Aura Obsidian import: DRY RUN ===\n");
console.log(`CSV rows read           : ${rows.length}`);
console.log(`Episodes to insert      : ${episodes.length}`);
console.log(`Severity samples        : ${sampleCount}`);
console.log(`Rows rejected           : ${errors.length}`);
console.log(`Onset time known        : ${timeKnown}/${episodes.length} (rest anchored at local noon, time marked unknown)`);
console.log(`Severity present        : ${withSeverity}/${episodes.length}`);
console.log(`Date range              : ${episodes[0]?.episode.local_date} .. ${episodes.at(-1)?.episode.local_date}`);
console.log(`Locations resolved      : ${[...places].join(" | ")}`);

console.log(`\nHeadache days per month (${Object.keys(byMonth).length} months):`);
for (const m of Object.keys(byMonth).sort()) console.log(`  ${m}  ${"#".repeat(byMonth[m])} ${byMonth[m]}`);

console.log(`\nQuarantined self_reported_type values (stored verbatim, parsed into NOTHING):`);
for (const t of [...quarantinedTypes].sort()) console.log(`  - ${t}`);

if (errors.length) {
  console.log(`\nREJECTED ROWS (${errors.length}):`);
  for (const e of errors) console.log(`  ! ${e}`);
}

const onsetWarnings = warnings.filter((w) => w.includes("onset not parseable"));
console.log(`\nAmbiguous onset, left unknown rather than guessed (${onsetWarnings.length}):`);
for (const w of onsetWarnings.slice(0, 10)) console.log(`  ~ ${w}`);
if (onsetWarnings.length > 10) console.log(`  ... and ${onsetWarnings.length - 10} more`);

const boundaryWarnings = warnings.filter((w) => w.includes("near a location boundary"));
console.log(`\nNear a location boundary, weather may be misattributed (${boundaryWarnings.length} dates)`);

// ── Emit SQL ────────────────────────────────────────────────────────────────
if (args.out) {
  const sql = [
    "-- Generated by scripts/import-obsidian.mjs. Idempotent: safe to re-run.",
    "-- CONTAINS PERSONAL HEALTH DATA. Do not commit.",
    "",
    ...episodes.map(episodeToSql),
    "",
  ].join("\n");
  writeFileSync(args.out, sql, "utf8");
  console.log(`\nSQL written to ${args.out} (${sql.length} bytes). Nothing has been applied.`);
  console.log(`Apply locally : npx wrangler d1 execute aura --local  --file=${args.out}`);
  console.log(`Apply to prod : npx wrangler d1 execute aura --remote --file=${args.out}`);
} else {
  console.log(`\nNo --out given, so no SQL was written. Nothing has been applied.`);
}
